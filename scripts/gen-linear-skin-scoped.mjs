#!/usr/bin/env node
/**
 * Generates app/linear-skin.generated.css from apps/linear/app/linear-components.css
 * scoped under :root[data-skin="linear"] for the main registry site.
 *
 * Uses a brace-aware walk so comments and declaration bodies are never
 * treated as selectors (the previous regex corrupted output).
 */
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const srcPath = path.join(root, "apps/linear/app/linear-components.css")
const outPath = path.join(root, "app/linear-skin.generated.css")
const scope = ':root[data-skin="linear"]'

const src = fs.readFileSync(srcPath, "utf8")

function scopeSelectors(selectors) {
  return selectors
    .split(",")
    .map((part) => {
      const trimmed = part.trim()
      if (!trimmed) return part
      if (trimmed.startsWith("@")) return trimmed
      return `${scope} ${trimmed}`
    })
    .join(",\n")
}

/**
 * Walk CSS and prefix every rule's selector list with the skin scope.
 * Skips @-rules' own selectors (keeps @media / @supports wrappers intact
 * and scopes nested rules inside them).
 */
function scopeCss(css) {
  let out = ""
  let i = 0
  const n = css.length

  while (i < n) {
    // Comments
    if (css[i] === "/" && css[i + 1] === "*") {
      const end = css.indexOf("*/", i + 2)
      const close = end === -1 ? n : end + 2
      out += css.slice(i, close)
      i = close
      continue
    }

    // @-rules: copy the prelude, then either a block (recurse) or a statement
    if (css[i] === "@") {
      let j = i
      while (j < n && css[j] !== "{" && css[j] !== ";") j++
      out += css.slice(i, j)
      if (j < n && css[j] === ";") {
        out += ";"
        i = j + 1
        continue
      }
      if (j < n && css[j] === "{") {
        // Find matching brace for the @-block
        let depth = 1
        let k = j + 1
        while (k < n && depth > 0) {
          if (css[k] === "/" && css[k + 1] === "*") {
            const end = css.indexOf("*/", k + 2)
            k = end === -1 ? n : end + 2
            continue
          }
          if (css[k] === "{") depth++
          else if (css[k] === "}") depth--
          k++
        }
        const inner = css.slice(j + 1, k - 1)
        out += "{\n" + scopeCss(inner) + "\n}"
        i = k
        continue
      }
      i = j
      continue
    }

    // Skip whitespace / newlines between rules
    if (/\s/.test(css[i])) {
      out += css[i]
      i++
      continue
    }

    // Regular rule: selectors { declarations }
    let j = i
    while (j < n && css[j] !== "{") {
      if (css[j] === "/" && css[j + 1] === "*") {
        const end = css.indexOf("*/", j + 2)
        j = end === -1 ? n : end + 2
        continue
      }
      j++
    }
    if (j >= n) {
      out += css.slice(i)
      break
    }

    const selectors = css.slice(i, j).trim()
    let depth = 1
    let k = j + 1
    while (k < n && depth > 0) {
      if (css[k] === "/" && css[k + 1] === "*") {
        const end = css.indexOf("*/", k + 2)
        k = end === -1 ? n : end + 2
        continue
      }
      if (css[k] === "{") depth++
      else if (css[k] === "}") depth--
      k++
    }
    const body = css.slice(j + 1, k - 1)
    out += scopeSelectors(selectors) + " {" + body + "}"
    i = k
  }

  return out
}

const scoped = scopeCss(src)
const header = `/* Generated by scripts/gen-linear-skin-scoped.mjs — do not edit */\n\n`
fs.writeFileSync(outPath, header + scoped)
console.log(`gen-linear-skin-scoped: wrote ${path.relative(root, outPath)}`)
